/**
 * One generator run, from the input tables to the file contents, without
 * writing anything. The command-line entry point writes what this returns; the
 * data test compares it with the committed seed files.
 */

import { readFileSync } from "node:fs";
import { join } from "node:path";

import {
  assertExpectations,
  type Expectation,
} from "../../catalog/expectations.js";
import { toCsv } from "../../reference-links/lib/csv.js";
import { parseCisaCsv, parseDropsCsv } from "./inputs.js";
import {
  affinitySql,
  buildOverlay,
  coverageSql,
  mappingsSql,
} from "./overlay.js";
import { summary, TUPLES_HEADER, tupleRows } from "./report.js";
import { REPORTS_DIR, SEED_DIR, SOURCES_DIR } from "./paths.js";
import { loadSeedContext } from "./seed.js";

export interface RunResult {
  files: {
    "09-zt-mappings.sql": string;
    "11-zt-part-coverage.sql": string;
    "13-zt-mapping-affinity.sql": string;
  };
  tuplesCsv: string;
  expectations: Expectation[];
  summary: string[];
}

type TupleFields = {
  controlId: string;
  pillar: string;
  function: string;
  maturity: string;
};

/** The controls whose every CISA tuple is in the drop list: the only controls a run may lose. */
export function controlsDroppedWhole(
  cisa: TupleFields[],
  drops: TupleFields[],
): number {
  const key = (t: TupleFields) =>
    [t.controlId, t.pillar, t.function, t.maturity].join("|");
  const dropped = new Set(drops.map(key));
  const byControl = new Map<string, string[]>();
  for (const row of cisa) {
    byControl.set(row.controlId, [
      ...(byControl.get(row.controlId) ?? []),
      key(row),
    ]);
  }
  return [...byControl.values()].filter((keys) =>
    keys.every((k) => dropped.has(k)),
  ).length;
}

export function runGenerator(
  dirs: { sources: string; reports: string; seed: string } = {
    sources: SOURCES_DIR,
    reports: REPORTS_DIR,
    seed: SEED_DIR,
  },
): RunResult {
  const read = (dir: string, f: string) => readFileSync(join(dir, f), "utf8");
  const seedDir = dirs.seed;
  const cisa = parseCisaCsv(read(dirs.sources, "cisa-ztmm-mapping.csv"));
  const drops = parseDropsCsv(read(dirs.sources, "intentional-drops.csv"));
  const findings =
    read(dirs.reports, "cisa-findings.csv").trim().split("\n").length - 1;
  const seed = loadSeedContext(seedDir);
  const overlay = buildOverlay({ cisa, drops, seed });
  const tupleCount = overlay.mappings.reduce((n, m) => n + m.tuples.length, 0);
  const cisaControls = new Set(cisa.map((r) => r.controlId)).size;
  const cisaTuples = new Set(
    cisa.map((r) => [r.controlId, r.pillar, r.function, r.maturity].join("|")),
  ).size;
  // Floors at what the inputs promise, so a run thinner than its inputs stops
  // here as well as in the reconciliation. Both come from the inputs alone: a drop
  // removes a tuple, and a control leaves only when every tuple CISA gives it is
  // dropped.
  const expectations: Expectation[] = [
    {
      name: "mapped controls",
      actual: overlay.mappings.length,
      floor: cisaControls - controlsDroppedWhole(cisa, drops),
    },
    {
      name: "affinity tuples",
      actual: tupleCount,
      floor: cisaTuples - drops.length,
    },
  ];
  assertExpectations("Zero Trust overlay", expectations);

  const provenance = [
    `Source: sources/zt-mapping/cisa-ztmm-mapping.csv (CISA, Zero Trust Maturity Model control mapping to NIST SP 800-53 Rev. 5;`,
    `  ${cisa.length} rows on ${cisaControls} controls), less sources/zt-mapping/intentional-drops.csv (${drops.length}):`,
    `  ${overlay.mappings.length} controls, ${tupleCount} tuples. Generated by prisma/generators/zt-overlay/generate.ts.`,
    `  Each tuple's rows, designations and fate are in reports/zt-overlay/tuples.csv.`,
  ];

  return {
    files: {
      "09-zt-mappings.sql": mappingsSql(overlay.mappings, provenance),
      "11-zt-part-coverage.sql": coverageSql(),
      "13-zt-mapping-affinity.sql": affinitySql(overlay.mappings, provenance),
    },
    tuplesCsv: toCsv(TUPLES_HEADER, tupleRows(overlay, seed.guidanceGroups)),
    expectations,
    summary: summary(overlay, seed.guidanceGroups, {
      cisaRows: cisa.length,
      findings,
    }),
  };
}
